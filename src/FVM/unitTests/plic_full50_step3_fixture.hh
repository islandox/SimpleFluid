inline std::vector<char> bytes(std::string_view h)
{
    std::vector<char> b;
    b.reserve(h.size() / 2);
    const auto n = [](char c) { return c <= '9' ? c - '0' : c - 'a' + 10; };
    for (std::size_t i = 0; i < h.size(); i += 2)
        b.push_back(char(n(h[i]) * 16 + n(h[i + 1])));
    return b;
}
