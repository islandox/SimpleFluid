/** Match the production sample contract: retain the smaller independent amount
 * and complement only its fitting label against the native geometric volume. */
inline Sample sample(const Row& row)
{
    const auto digit = [](char c) { return c <= '9' ? c - '0' : c - 'a' + 10; };
    std::vector<char> bytes;
    bytes.reserve(row.certificate.size() / 2);
    for (std::size_t i = 0; i < row.certificate.size(); i += 2)
        bytes.push_back(char((digit(row.certificate[i]) << 4) | digit(row.certificate[i + 1])));
    const auto geometry = PLIC::ConvexCellGeometry<ArithmeticMode::Ordinary>::decode_certificate(bytes);
    const bool gas_minor = row.physical_gas <= row.physical_carrier;
    const double minority = gas_minor ? row.physical_gas : row.physical_carrier;
    const double dominant = double(geometry->volume().value - minority);
    return {geometry, gas_minor ? minority : dominant, gas_minor ? dominant : minority, row.id, row.mixed};
}
