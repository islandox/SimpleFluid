/** Dense diagnostic index across the three independent census categories. */
constexpr unsigned contact_payload_role_count() noexcept
{
    return static_cast<unsigned>(BasicContactPayloadRole::Count) +
           static_cast<unsigned>(ParallelSupportPayloadRole::Count) +
           static_cast<unsigned>(GeometryContactPayloadRole::Count);
}
constexpr unsigned contact_payload_role_index(ContactPayloadRole role) noexcept
{
    switch (role.category())
    {
        case ContactPayloadCategory::Basic:
            return static_cast<unsigned>(role.ordinal());
        case ContactPayloadCategory::ParallelSupport:
            return static_cast<unsigned>(role.ordinal()) + static_cast<unsigned>(BasicContactPayloadRole::Count);
        case ContactPayloadCategory::Geometry:
            return static_cast<unsigned>(role.ordinal()) + static_cast<unsigned>(BasicContactPayloadRole::Count) +
                   static_cast<unsigned>(ParallelSupportPayloadRole::Count);
    }
    return 0;
}
/** Inverse of contact_payload_role_index; diagnostics only. */
constexpr ContactPayloadRole contact_payload_role_at(unsigned index) noexcept
{
    if (index < static_cast<unsigned>(BasicContactPayloadRole::Count))
        return ContactPayloadRole(static_cast<BasicContactPayloadRole>(index));
    index -= static_cast<unsigned>(BasicContactPayloadRole::Count);
    if (index < static_cast<unsigned>(ParallelSupportPayloadRole::Count))
        return ContactPayloadRole(static_cast<ParallelSupportPayloadRole>(index));
    return ContactPayloadRole(
        static_cast<GeometryContactPayloadRole>(index - static_cast<unsigned>(ParallelSupportPayloadRole::Count)));
}
